export function braille(dots: readonly string[]): string {
  return dots
    .map((d) =>
      String.fromCharCode(
        0x2800 +
          Array.from(d).reduce(
            (n, c) => (c === "0" ? n : n | (1 << (Number(c) - 1))),
            0,
          ),
      ),
    )
    .join("");
}
