// Reproduce the validation inventory from the already locked pinyin-pro 3.29.4 dictionary.
// This is a dictionary-supported spelling inventory, not a claim of all Mandarin readings.
import { pinyin } from 'pinyin-pro';
import { writeFile, readFile } from 'node:fs/promises';
const syllables = new Set();
for (let code = 0x3400; code <= 0x323af; code++) {
  const character = String.fromCodePoint(code);
  if (!/^\p{Script=Han}$/u.test(character)) continue;
  for (const reading of pinyin(character, {type:'array',toneType:'none',multiple:true}))
    if (/^[a-zü]+$/.test(reading)) syllables.add(reading);
}
const content = '// Generated by scripts/generate-reading-inventory.mjs from pinyin-pro 3.29.4.\n' +
  '// Dictionary-supported spellings; encoder support is additionally checked at validation.\n' +
  'export const READING_SPELLINGS = new Set(' + JSON.stringify([...syllables].sort().join(' ')) + '.split(" "));\n';
const file = 'packages/core/src/language/reading-inventory.ts';
if (process.argv.includes('--check')) {
  if (await readFile(file,'utf8') !== content) throw new Error('Reading inventory differs from locked dictionary');
} else await writeFile(file,content);
console.log(`Verified ${syllables.size} dictionary spellings`);
